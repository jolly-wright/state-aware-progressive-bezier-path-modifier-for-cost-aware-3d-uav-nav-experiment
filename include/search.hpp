#pragma once
#include "types.hpp"
#include "config.hpp"
namespace uav::search {
// ============================================================================
// SEARCH RUNTIME
// ============================================================================
struct SearchRuntime
{
    // Maximum wall-clock time that this progressive search call may consume.
    // INF means no execution-time horizon is imposed.
    double remainingExecutionTime = INF;
    // Maximum distance that the UAV may travel during the available
    // execution horizon.
    // INF means no travel-distance horizon is imposed.
    double availableTravelDistance = INF;
};
// ============================================================================
// SEARCH PROGRESS
// ============================================================================
//
// These callbacks allow main.cpp to receive real search-stage messages while
// progressiveModify() is actually running.
//
// No debug candidate collection is performed.
// Only compact progress information is reported.
//
enum class SearchStage
{
    Stage1Done,
    Stage3Started,
    Stage3Done,
    Stage3Skipped,
    SegmentAccepted,
    SearchFinished
};
struct SearchProgress
{
    SearchStage stage =
        SearchStage::SearchFinished;
    std::size_t cornerIndex = 0;
    std::size_t stage1CandidateEvaluations = 0;
    std::size_t stage3CandidateEvaluations = 0;
    std::size_t refinementIterations = 0;
    double maxCurvature = 0.0;
    double lateralAcceleration = 0.0;
    double Jd = 0.0;
    double Jk = 0.0;
    double Jl = 0.0;
    double J = INF;
    double segmentGenerationTimeMs = 0.0;
};
// ============================================================================
// PROGRESS CALLBACK
// ============================================================================
using SearchProgressCallback =
    void (*)(
        const SearchProgress& progress,
        void* userData
    );
// ============================================================================
// SEARCH INPUT
// ============================================================================
struct SearchInput
{
    const WaypointPath* upstreamPath = nullptr;
    const Map3D* map = nullptr;
    UAVState state;
    config::VehicleConfig vehicle;
    SearchRuntime runtime;
    // First upstream waypoint to be incorporated.
    //
    // Waypoint 0 is the UAV starting position.
    //
    // Therefore the first generated segment normally searches:
    //
    // P0 = upstreamPath[0]
    // P3 = upstreamPath[1]
    //
    std::size_t startCornerIndex = 1;
    // P0 of the first segment generated by this search call.
    Vec3 P0;
    // Whether a previously accepted Bézier segment exists.
    bool hasPreviousSegment = false;
    BezierSegment previousSegment;
    // Corner associated with the previous committed segment.
    Vec3 previousCorner;
    // Optional progress callback.
    //
    // If nullptr, no progress messages are generated.
    SearchProgressCallback progressCallback = nullptr;
    // User-supplied callback context.
    void* progressUserData = nullptr;
};
// ============================================================================
// SEARCH STATISTICS
// ============================================================================
struct SearchStatistics
{
    std::size_t stage1CandidateEvaluations = 0;
    std::size_t stage3CandidateEvaluations = 0;
    std::size_t refinementIterations = 0;
};
// ============================================================================
// PROGRESSIVE MODIFIER
// ============================================================================
ModifierResult progressiveModify(
    const SearchInput& input
);
} // namespace uav::search