# ============================================================================
# MAIN
# ============================================================================

def main() -> None:
    """
    Generate all experimental scenarios and their Plotly visualizations.
    """

    scenarios = build_experimental_scenarios()

    print(
        f"Generating {len(scenarios)} scenarios..."
    )

    for scenario in scenarios:

        scenario_id = scenario["scenario_id"]

        # ------------------------------------------------------------
        # Generate JSON
        # ------------------------------------------------------------

        json_path = save_scenario(
            scenario
        )

        # ------------------------------------------------------------
        # Generate Plotly HTML from the SAME scenario dictionary
        # ------------------------------------------------------------

        html_path = save_input_visualization(
            scenario
        )

        print(
            f"Scenario {scenario_id}:"
        )

        print(
            f"    JSON: {json_path}"
        )

        print(
            f"    HTML: {html_path}"
        )

    print()
    print("Generation complete.")


if __name__ == "__main__":
    main()