#!/usr/bin/env python3

"""
input.py
========

Python-side scenario generator for the UAV trajectory-modification
experiments.

Purpose
-------
Create validated JSON scenario files that are consumed by the C++ planner.

In addition to generating the JSON input files, this script generates
interactive Plotly HTML visualizations of the same scenarios.

This file DOES NOT:
    - perform path planning
    - perform collision checking
    - generate Bézier curves
    - evaluate the cost function
    - simulate UAV execution

Those operations belong to the C++ implementation.

Coordinate convention
---------------------
All spatial quantities are expressed in metres unless explicitly stated
otherwise.

Scenario path convention
-------------------------
    C0 = initial UAV position
    C1 ... C(N-1) = upstream path corners
    CN = final destination

For the first generated Bézier segment:
    P0 = C0

For subsequent generated Bézier segments:
    P0 = B_previous(1)

Therefore, subsequent UAV positions / segment starting points are NOT
specified in this input file. They are generated by the C++ progressive
planner from the previously generated Bézier segment.

Obstacle representation
------------------------
Every obstacle is an axis-aligned rectangular box represented by:

    center     = [x, y, z]
    dimensions = [Dx, Dy, Dz]

The C++ implementation derives the minimum and maximum corners from these
values.
"""

from __future__ import annotations

import json
from pathlib import Path
from typing import Sequence

import plotly.graph_objects as go


# ============================================================================
# OUTPUT DIRECTORIES
# ============================================================================

# Scenario JSON files.
OUTPUT_DIR = Path("scenarios")

# Plotly HTML visualization files.
VISUALIZATION_DIR = Path("input_visualization")


# ============================================================================
# BASIC VALIDATION HELPERS
# ============================================================================

def _validate_vector3(
    value: Sequence[float],
    name: str,
) -> list[float]:
    """
    Validate and normalize a 3-dimensional vector.
    """

    if not isinstance(value, (list, tuple)):
        raise ValueError(
            f"{name} must be a list or tuple of three numbers."
        )

    if len(value) != 3:
        raise ValueError(
            f"{name} must contain exactly three values."
        )

    try:
        vector = [float(x) for x in value]
    except (TypeError, ValueError) as exc:
        raise ValueError(
            f"{name} must contain only numeric values."
        ) from exc

    return vector


def _validate_positive_vector3(
    value: Sequence[float],
    name: str,
) -> list[float]:
    """
    Validate a 3-D vector whose components must all be positive.
    """

    vector = _validate_vector3(value, name)

    if any(x <= 0.0 for x in vector):
        raise ValueError(
            f"{name} must contain only positive values."
        )

    return vector


# ============================================================================
# SCENARIO VALIDATION
# ============================================================================

def validate_scenario(scenario: dict) -> None:
    """
    Validate the complete scenario structure before writing it to JSON.

    This intentionally validates only the INPUT CONTRACT.

    It does not determine whether:
        - the upstream path is collision-free,
        - the Bézier modifier can find a valid trajectory,
        - the path satisfies the lateral-acceleration constraint,
        - the B-spline baseline succeeds.
    """

    # ------------------------------------------------------------------------
    # Scenario ID
    # ------------------------------------------------------------------------

    if "scenario_id" not in scenario:
        raise ValueError("Missing 'scenario_id'.")

    if not isinstance(scenario["scenario_id"], int):
        raise ValueError("'scenario_id' must be an integer.")

    if scenario["scenario_id"] < 0:
        raise ValueError("'scenario_id' must be non-negative.")

    # ------------------------------------------------------------------------
    # UAV
    # ------------------------------------------------------------------------

    if "uav" not in scenario:
        raise ValueError("Missing 'uav' section.")

    uav = scenario["uav"]

    required_uav_fields = {
        "dimensions",
        "position",
        "velocity",
        "max_velocity",
        "max_lateral_acceleration",
    }

    missing = required_uav_fields - uav.keys()

    if missing:
        raise ValueError(
            f"Missing UAV fields: {sorted(missing)}"
        )

    dimensions = _validate_positive_vector3(
        uav["dimensions"],
        "uav.dimensions",
    )

    position = _validate_vector3(
        uav["position"],
        "uav.position",
    )

    velocity = _validate_vector3(
        uav["velocity"],
        "uav.velocity",
    )

    try:
        max_velocity = float(uav["max_velocity"])
        max_lateral_acceleration = float(
            uav["max_lateral_acceleration"]
        )
    except (TypeError, ValueError) as exc:
        raise ValueError(
            "UAV velocity limits must be numeric."
        ) from exc

    if max_velocity <= 0.0:
        raise ValueError(
            "uav.max_velocity must be greater than zero."
        )

    if max_lateral_acceleration <= 0.0:
        raise ValueError(
            "uav.max_lateral_acceleration must be greater than zero."
        )

    # ------------------------------------------------------------------------
    # MAP
    # ------------------------------------------------------------------------

    if "map" not in scenario:
        raise ValueError("Missing 'map' section.")

    map_data = scenario["map"]

    if "resolution_cm" not in map_data:
        raise ValueError(
            "Missing 'map.resolution_cm'."
        )

    try:
        resolution_cm = float(map_data["resolution_cm"])
    except (TypeError, ValueError) as exc:
        raise ValueError(
            "'map.resolution_cm' must be numeric."
        ) from exc

    if resolution_cm <= 0.0:
        raise ValueError(
            "'map.resolution_cm' must be greater than zero."
        )

    if "obstacles" not in map_data:
        raise ValueError(
            "Missing 'map.obstacles'."
        )

    if not isinstance(map_data["obstacles"], list):
        raise ValueError(
            "'map.obstacles' must be a list."
        )

    # ------------------------------------------------------------------------
    # Obstacles
    # ------------------------------------------------------------------------

    for index, obstacle in enumerate(map_data["obstacles"]):

        prefix = f"map.obstacles[{index}]"

        if not isinstance(obstacle, dict):
            raise ValueError(
                f"{prefix} must be an object."
            )

        if "center" not in obstacle:
            raise ValueError(
                f"Missing '{prefix}.center'."
            )

        if "dimensions" not in obstacle:
            raise ValueError(
                f"Missing '{prefix}.dimensions'."
            )

        _validate_vector3(
            obstacle["center"],
            f"{prefix}.center",
        )

        _validate_positive_vector3(
            obstacle["dimensions"],
            f"{prefix}.dimensions",
        )

    # ------------------------------------------------------------------------
    # PATH
    # ------------------------------------------------------------------------

    if "path" not in scenario:
        raise ValueError("Missing 'path' section.")

    path = scenario["path"]

    if "waypoints" not in path:
        raise ValueError(
            "Missing 'path.waypoints'."
        )

    waypoints = path["waypoints"]

    if not isinstance(waypoints, list):
        raise ValueError(
            "'path.waypoints' must be a list."
        )

    # At minimum:
    #
    #     C0 = start
    #     C1 = destination
    #
    # Additional entries represent intermediate upstream corners.
    if len(waypoints) < 2:
        raise ValueError(
            "'path.waypoints' must contain at least C0 and CN."
        )

    validated_waypoints = []

    for index, waypoint in enumerate(waypoints):

        validated_waypoints.append(
            _validate_vector3(
                waypoint,
                f"path.waypoints[{index}]",
            )
        )

    # ------------------------------------------------------------------------
    # C0 consistency
    # ------------------------------------------------------------------------
    #
    # C0 is the initial UAV position.
    #
    # Therefore:
    #
    #     UAV.position == C0
    #
    # ------------------------------------------------------------------------

    tolerance = 1e-9

    for axis in range(3):

        if abs(
            position[axis] - validated_waypoints[0][axis]
        ) > tolerance:

            raise ValueError(
                "uav.position must be identical to path.waypoints[0] "
                "(C0)."
            )


# ============================================================================
# SCENARIO CREATION
# ============================================================================

def create_scenario(
    scenario_id: int,
    dimensions: Sequence[float],
    position: Sequence[float],
    velocity: Sequence[float],
    max_velocity: float,
    max_lateral_acceleration: float,
    map_resolution_cm: float,
    obstacles: list[dict],
    waypoints: list[Sequence[float]],
) -> dict:
    """
    Construct a complete scenario dictionary.
    """

    scenario = {
        "scenario_id": int(scenario_id),

        "uav": {
            "dimensions": list(dimensions),
            "position": list(position),
            "velocity": list(velocity),
            "max_velocity": float(max_velocity),
            "max_lateral_acceleration": float(
                max_lateral_acceleration
            ),
        },

        "map": {
            "resolution_cm": float(map_resolution_cm),
            "obstacles": obstacles,
        },

        "path": {
            "waypoints": [
                list(waypoint)
                for waypoint in waypoints
            ],
        },
    }

    validate_scenario(scenario)

    return scenario


# ============================================================================
# JSON OUTPUT
# ============================================================================

def save_scenario(
    scenario: dict,
    output_directory: Path = OUTPUT_DIR,
) -> Path:
    """
    Validate and save a scenario as a formatted JSON file.

    Example:
        scenarios/scenario_001.json
    """

    validate_scenario(scenario)

    output_directory.mkdir(
        parents=True,
        exist_ok=True,
    )

    scenario_id = scenario["scenario_id"]

    output_path = (
        output_directory /
        f"scenario_{scenario_id:03d}.json"
    )

    with output_path.open(
        "w",
        encoding="utf-8",
    ) as file:

        json.dump(
            scenario,
            file,
            indent=4,
        )

    return output_path


# ============================================================================
# PLOTLY BOX
# ============================================================================

def _add_box(
    figure: go.Figure,
    center: Sequence[float],
    dimensions: Sequence[float],
    name: str,
    color: str,
    opacity: float,
) -> None:
    """
    Add an axis-aligned rectangular box to a Plotly 3-D figure.

    center:
        [cx, cy, cz]

    dimensions:
        [Dx, Dy, Dz]
    """

    cx, cy, cz = center
    dx, dy, dz = dimensions

    xmin = cx - dx / 2.0
    xmax = cx + dx / 2.0

    ymin = cy - dy / 2.0
    ymax = cy + dy / 2.0

    zmin = cz - dz / 2.0
    zmax = cz + dz / 2.0

    vertices = [
        [xmin, ymin, zmin],  # 0
        [xmax, ymin, zmin],  # 1
        [xmax, ymax, zmin],  # 2
        [xmin, ymax, zmin],  # 3
        [xmin, ymin, zmax],  # 4
        [xmax, ymin, zmax],  # 5
        [xmax, ymax, zmax],  # 6
        [xmin, ymax, zmax],  # 7
    ]

    x = [vertex[0] for vertex in vertices]
    y = [vertex[1] for vertex in vertices]
    z = [vertex[2] for vertex in vertices]

    # Two triangles per face.
    i = [
        0, 0,
        4, 4,
        0, 0,
        1, 1,
        2, 2,
        3, 3,
    ]

    j = [
        1, 2,
        5, 6,
        1, 4,
        2, 5,
        3, 6,
        0, 7,
    ]

    k = [
        2, 3,
        6, 7,
        4, 5,
        5, 6,
        7, 4,
        4, 7,
    ]

    figure.add_trace(
        go.Mesh3d(
            x=x,
            y=y,
            z=z,
            i=i,
            j=j,
            k=k,
            name=name,
            color=color,
            opacity=opacity,
            flatshading=True,
            hovertemplate=(
                f"{name}<br>"
                "x: %{x:.3f} m<br>"
                "y: %{y:.3f} m<br>"
                "z: %{z:.3f} m"
                "<extra></extra>"
            ),
        )
    )


# ============================================================================
# PLOTLY VISUALIZATION
# ============================================================================

def create_input_visualization(
    scenario: dict,
) -> go.Figure:
    """
    Create the Plotly 3-D visualization directly from the scenario
    dictionary.

    Displayed elements:

        Red boxes    -> obstacles
        Blue dots    -> upstream waypoints
        Purple box   -> UAV at uav.position
        Green box    -> final goal at path.waypoints[-1]
    """

    scenario_id = scenario["scenario_id"]

    uav = scenario["uav"]
    map_data = scenario["map"]
    waypoints = scenario["path"]["waypoints"]

    figure = go.Figure()

    # ------------------------------------------------------------------------
    # Obstacles
    # ------------------------------------------------------------------------

    for index, obstacle in enumerate(
        map_data["obstacles"],
        start=1,
    ):

        _add_box(
            figure=figure,
            center=obstacle["center"],
            dimensions=obstacle["dimensions"],
            name=f"Obstacle {index}",
            color="red",
            opacity=0.45,
        )

    # ------------------------------------------------------------------------
    # UAV
    # ------------------------------------------------------------------------
    #
    # IMPORTANT:
    # This uses uav.position from the scenario directly.
    #
    # It does NOT use path.waypoints[0] for visualization.
    #
    # validate_scenario() guarantees that:
    #
    #     uav.position == path.waypoints[0]
    #
    # ------------------------------------------------------------------------

    _add_box(
        figure=figure,
        center=uav["position"],
        dimensions=uav["dimensions"],
        name="UAV",
        color="purple",
        opacity=0.85,
    )

    # ------------------------------------------------------------------------
    # Waypoints
    # ------------------------------------------------------------------------

    waypoint_x = []
    waypoint_y = []
    waypoint_z = []
    waypoint_labels = []

    for index, waypoint in enumerate(waypoints):

        waypoint_x.append(waypoint[0])
        waypoint_y.append(waypoint[1])
        waypoint_z.append(waypoint[2])

        waypoint_labels.append(
            f"C{index}"
        )

    figure.add_trace(
        go.Scatter3d(
            x=waypoint_x,
            y=waypoint_y,
            z=waypoint_z,
            mode="markers",
            name="Waypoints",
            marker=dict(
                color="blue",
                size=7,
            ),
            text=waypoint_labels,
            hovertemplate=(
                "%{text}<br>"
                "x: %{x:.3f} m<br>"
                "y: %{y:.3f} m<br>"
                "z: %{z:.3f} m"
                "<extra></extra>"
            ),
        )
    )

    # ------------------------------------------------------------------------
    # Waypoint connecting line
    # ------------------------------------------------------------------------
    #
    # This is only a visual representation of the upstream waypoint path.
    # It is NOT a generated Bézier trajectory.
    # ------------------------------------------------------------------------

    figure.add_trace(
        go.Scatter3d(
            x=waypoint_x,
            y=waypoint_y,
            z=waypoint_z,
            mode="lines",
            name="Upstream waypoint path",
            line=dict(
                color="blue",
                width=3,
                dash="dot",
            ),
            showlegend=False,
            hoverinfo="skip",
        )
    )

    # ------------------------------------------------------------------------
    # Goal
    # ------------------------------------------------------------------------
    #
    # The final waypoint CN is the destination.
    #
    # The goal box uses the UAV dimensions so that its displayed physical
    # size is directly tied to the configured UAV dimensions.
    # ------------------------------------------------------------------------

    goal = waypoints[-1]

    _add_box(
        figure=figure,
        center=goal,
        dimensions=uav["dimensions"],
        name="End goal",
        color="green",
        opacity=0.75,
    )

    # ------------------------------------------------------------------------
    # Layout
    # ------------------------------------------------------------------------

    figure.update_layout(
        title=(
            f"UAV Input Visualization — "
            f"Scenario {scenario_id}"
        ),

        scene=dict(
            xaxis=dict(
                title="X (m)",
            ),
            yaxis=dict(
                title="Y (m)",
            ),
            zaxis=dict(
                title="Z (m)",
            ),
            aspectmode="data",
        ),

        margin=dict(
            l=0,
            r=0,
            t=50,
            b=0,
        ),

        legend=dict(
            x=0.01,
            y=0.99,
        ),
    )

    return figure


# ============================================================================
# SAVE PLOTLY VISUALIZATION
# ============================================================================

def save_input_visualization(
    scenario: dict,
    output_directory: Path = VISUALIZATION_DIR,
) -> Path:
    """
    Generate and save the interactive Plotly HTML visualization.
    """

    output_directory.mkdir(
        parents=True,
        exist_ok=True,
    )

    scenario_id = scenario["scenario_id"]

    output_path = (
        output_directory /
        f"scenario_{scenario_id:03d}.html"
    )

    figure = create_input_visualization(
        scenario
    )

    figure.write_html(
        str(output_path),
        include_plotlyjs=True,
        full_html=True,
    )

    return output_path


